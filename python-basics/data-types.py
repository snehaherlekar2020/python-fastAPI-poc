# 1. String (Text) - Always wrapped in quotes
project_name = "My FastAPI App"

# 2. Integer (Whole numbers)
port_number = 8000

# 3. Float (Decimal numbers)
api_version = 1.0

# 4. Boolean (True or False) - Must be capitalized!
is_server_running = True

# You can print these values to your terminal
print(project_name)
print(port_number)
print(api_version)
print(is_server_running)